		<h2 id="tourDeJeux">Les tours de jeux</h2>
		<p>
			Sagamore fonctionne en tour de jeu. Pour effectuer des actions, votre personnage aura 4 types
			de ressources à dépenser :
		</p>
		<ul class="grid list-decimal grid-cols-2 pl-8 text-sm font-bold">
			<li>Les faveurs diplomatiques</li>
			<li>La connaissance tactique</li>
			<li>Les points d’administration</li>
			<li>L’argent</li>
		</ul>

		<p>Tant que vous avez des points, vous pouvez programmer autant d’actions que vous voulez.</p>

		<p>
			Un tour de jeu se passe entre les phases de votations. Il y a une phase de votations à chaque
			heure. Une heure de jeu équivaut à 10 ans de vie dans le monde de Sagamore. Le jeu durera
			entre 12 et 15 heures, ce qui a pour conséquence que vous changerez au moins une fois de
			personnage durant le jeu. Tous les détails de l’héritage sont expliqués plus loin.
		</p>

		<p>
			Le jeu se déroule ainsi : une phase de votation, puis les arbitres annoncent les conséquences
			des votations. Une phase du choix de vos actions, puis les arbitres annoncent les conséquences
			de vos actions. Il y a un moment de battement entre chaque phase.
		</p>
