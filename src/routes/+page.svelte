		<h1>Introduction</h1>
		<h2>Note d'Intention</h2>
		<h3>En Résumé</h3>
		<p>
			Sagamore est un jeu de rôle grandeur nature de type Parlor LARP. Ses mécaniques de jeux
			mettent l’emphase sur les interactions spéciales plutôt que l’action pour résoudre les
			situations. Cela n’empêche pas des scènes d’actions de se produire, mais elles restent
			facultatives. Le thème principal est l’intrigue politique. Si vous avez aimez Game of Thrones,
			vous aimerez Sagamore.
		</p>
		<h3>Un univers médiéval fantaisie</h3>
		<p>
			La genèse de Sagamore s’installe dans une ambiance d’héroïque fantaisie, à savoir que l’on va
			retrouver des espèces fantastiques, typiquement des elfes. Cependant la magie est peu présente
			et souvent imperceptible pour la plupart des peuples de Sagamore. Sagamore est un royaume
			constitué de quatre duchés : Pique, Cœur, Carreau, Trèfle. Ils collaborent constamment tout en
			se constituant en rivaux.
		</p>
		<h3>Les dynasties</h3>
		<p>
			Les PJS (personnages joueu.r.se.s) incarnent un.e membre de la cour du Royaume. Les Pjs
			représentent également une dynastie. Ainsi, iels doivent toujours jongler entre le désir de
			faire évoluer sa dynastie et garantir la pérennité du royaume. Tout l’intérêt du jeu réside
			dans cet équilibre. Pour cela, iels ont une panoplie d’actions pour influencer sur les autres
			PJs ou l’Empire
		</p>
		<h2>Les Trois piliers de Sagamore</h2>
		<h3>Gestion Du domaine</h3>
		<p>
			Chaque Dynastie possède au moins un domaine à gérer, à savoir s’occuper de ses ressources et
			de la population. Vous pouvez être plusieurs PJs au sein d’une seule dynastie. Votre domaine
			sera plus ou moins grand en fonction de votre titre. Voici les titres : Reine, Duchesse,
			Comtesse.
		</p>
		<h3>Le Pouvoir de la Lignée</h3>
		<p>
			Chaque PJ recevra un pouvoir de Lignée aléatoire. Un pouvoir de lignée est représenté par une
			carte de jeu (Roi, Dame, valet, etc..). Ils permettent d’influencer le jeu de manière
			conséquente. Mais si vous vous faites attraper en cours d’utilisation, vous perdrez votre
			pouvoir.
		</p>
		<h3>Les Votations</h3>
		<p>
			Des évènements surviendront régulièrement au cours du jeu. Pour y répondre, l’Impératrice
			pourra décréter des mesures. Mais ces mesures doivent toujours être validés par la Cour. Ce
			sont les moments les plus importants du jeu car elles définissent le futur de l’Empire.
		</p>
		<h2>Un jeu bac à sable</h2>
		<p>
			Sagamore n’aura pas de trame principale, c’est à vous de définir les objectifs de votre
			dynastie. Sagamore se veut un jeu de simulation de gestion de Royaume avec une grande liberté.
			Si l’Empire commence avec un système féodale classique et patriciale, il est à votre
			convenance de faire ne sorte que tout le système change.
		</p>
		<h2 id="infosPratiques">Infos Pratiques</h2>
		<p>Des infos supplémentaires sur l'organisation viendront avec le temps.</p>
		<h3>Date</h3>
		<p>
			J’y serais du jeudi 13 août au dimanche 16. Le jeu, en lui-même, commence le vendredi soir et
			se finira samedi soir. Vous avez donc la possibilité de venir plus tôt pour profiter du bon
			air de la montagne.
		</p>
		<h3>Lieu</h3>
		<p>
			Le Gn se fera à Verdy, au chalet de mes parents, c’est à peu près trois quarts d’heure de
			Genève en Haute-Savoie.
		</p>
		<h3>Bouffe</h3>
		<p>
			Je ne fournirais pas de repas ni de boisson. On va vitre sur mode repas canadien. En revanche,
			chaque midi et chaque soir, il y aura un barbecue allumé à disposition. Ça me ferait très
			plaisir de faire un weekend vegan.
		</p>
		<h3>Couchage</h3>
		<p>
			Pour le couchage, il n’y aura pas de lits pour tout le monde, donc une dizaine de personnes
			devront dormir sous tente.
		</p>
