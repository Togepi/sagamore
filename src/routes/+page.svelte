		</p>

		<h1 id="reglesSecurite">Règles de sécurité</h1>
		<h2 id="securitePhysique">Sécurité physique</h2>
		<h3>La sécurité en priorité</h3>
		<p>
			Nous jouons ensemble. Il s’agit d’un JEU. Toute situation mettant en danger quelqu’un doit
			être évitée, et doit mener à un bref arrêt du jeu. Par exemple, si deux personnes combattent
			trop près d’un ravin, elles ne doivent pas hésiter à faire une pause dans le jeu pour se
			déplacer et poursuivre leur combat dans un lieu plus sécurisé. De même, il est dangereux de
			mettre sa propre santé en danger afin de préserver celle de son personnage… En cas de
			problème, les Orgas sont présentes, et il est bon de les avertir, car iels ont souvent des
			solutions à proposer (d’ordre médical, logistique, etc.).
		</p>
		<h3>Les armes de jeu</h3>
		<p>
			Les combats en jeu se font à l’aide d’armes spécialement créées pour le GN. Toutes les armes
			sont vérifiées avant le jeu par les Orgas du GN. Les armes doivent être conçues en mousse (ou
			matériaux similaires) pour être acceptées. Celles qui contiennent une fibre de verre ou de
			carbone ne peuvent en aucun cas être lancées, et aucun coup d’estoc ne peut être porté avec.
		</p>
		<h3>Les attaques</h3>
		<p>
			TOUS LES COUPS DOIVENT ÊTRE RETENUS! Même une arme de GN fait mal lorsque l’on utilise
			beaucoup de force pour frapper avec. Si une PJ ne respecte pas ces règles de sécurité, il est
			possible d’en avertir les Organisateurs, qui calmeront son bras trop puissant.
		</p>
		<h3>Respecter le périmètre</h3>
		<p>
			Au début de chaque GN, les Orgas définissent un périmètre de jeu; ces limites ne doivent être
			dépassées en aucun cas. Aucune scène du jeu n’aura lieu en dehors de cette zone, rien n’y sera
			caché, donc il n’y a absolument rien à y faire. La plupart du temps, l’aire de jeu est limitée
			pour des raisons de sécurité ou de légalité (il serait ennuyeux pour une voisine de voir
			quinze GNistes dans son jardin un dimanche matin…). De manière générale, lorsque les Orgas
			donnent des instructions, elles ont lieu d’être et doivent être respectées, que ce soit avant,
			après ou durant le GN. C’est particulièrement pertinent cette année car une partie du terrain
			(caché, nous serons en intimité) sera utilisée par les scouts.
		</p>
		<h3>Le matériel</h3>
		<p>
			Enfin, le respect des autres s’étend également à leur matériel. Les armes, accessoires et
			costumes de GN sont chers à acheter, et longs à créer; il est normal d’y faire attention, et
			d’en prendre soin. Typiquement, lorsque des armes traînent par terre sur un champ de bataille
			(flèches, le plus souvent), il est bon de les écarter rapidement des pieds des barbares, si
			c’est possible.
		</p>
		<h2 id="securiteEmotionelle">Sécurité émotionelle</h2>
		<h3>Prévenir plutôt que guérir</h3>
		<p>
			Merci de bien indiquer si un sujet vous est particulièrement sensible. Nous prenons en compte
			les besoins émotionnels de chaque personne et adaptons au maximum l’univers et le scénario en
			fonction de ceux-ci. Si, malgré toutes les précautions prises, la personne se sent
			inconfortable, merci de prévenir l’équipe le plus rapidement possible afin que nous puissions
			prendre les dispositions nécessaires.
		</p>
		<h4>Voici les thèmes qui sont abordés lors de ce WE :</h4>
		<ul class=" grid grid-cols-2 pt-8 text-sm font-bold *:h-12">
			<li>Violence et agression (pouvant mener à la mort)</li>
			<li>Visuel gore (sang, organe)</li>
			<li>Auto-mutilation</li>
			<li>Maladie léthale</li>
			<li>Famine</li>
			<li>Torture</li>
			<li>Génocide</li>
			<li>Paralysie / claustrophobie</li>
			<li>Mort-vivant</li>
			<li>Suicide</li>
			<li>Trouble psychique (schizophrénie, paranoïa,…)</li>
			<li>Désastre naturel</li>
			<li>Violence spéciste</li>
			<li>Nudité</li>
			<li>Sonorité forte (explosion, alarme)</li>
			<li>Lumière stroboscopique</li>
		</ul>
		<h3>En fonction des demandes</h3>
		<p>
			En fonction des demandes, ces thèmes peuvent potentiellement disparaître. Gardez en tête que
			l’idée de ce Gn est de se rapprocher du drame et que ces thématiques ne seront pas abordées
			sous un abord superficiel. Pour que nous puissions vous garantir une richesse émotionnelle
			lors de ce WE, merci de communiquer le plus tôt possible si une thématique vous intéresse ou
			vous repousse. Nous mettons le maximum de mesures pour prévenir tout inconfort, mais la
			communication reste le vecteur principal de toute sécurité.
		</p>

		<h3>Safe zone</h3>
		<p>
			Une salle spéciale sera dédiée au repos et sera considérée comme hors-jeu tout le we. Nous
			vous indiquerons la salle pendant la présentation du jeu. Ce n’est pas une salle de détente
			mais de repos. Les personnes qui ressentent la nécessité de l’utiliser doivent pouvoir le
			faire en y retrouvant de la quiétude. Pour un espace détente, nous vous invitons à vous poser
			à la taverne.
		</p>

		<h3>Safeword et safegeste</h3>
		<p>
			Le concept du safeword permet d’exprimer son inconfort. Une fois qu’il est exprimé, les
			personnes autour doivent s’arrêter de jouer. Le jeu ne reprend qu’une fois assuré du bien-être
			de la personne. Le safeword est donc “vraiment vraiment”. Si une personne dit qu’elle est
			“vraiment vraiment gênée”, alors l’allocutaire doit considérer que c’est la PJ et non le
			personnage qui s’exprime, et prend les dispositions nécessaires. Le safegeste est le même
			concept mais appliqué à un geste, à savoir aux deux bras qui se croisent.
		</p>
		<h2 id="faireplay">Fairplay</h2>
		<h3>Jouer le jeu</h3>
		<p>
			Ce terme définit l’art de se mettre dans la peau d’un personnage, et d’agir comme lui le
			ferait, et non comme le joueur l’interprétant a l’habitude de le faire. Il concerne également
			la capacité de la joueuse à faire abstraction de ce que lui sait et que son personnage ignore.
			Enfin, il englobe toute la partie fair-play d’un GN, à savoir se laisser voler, tromper, tuer
			lorsque c’est le moment.
		</p>

		<h3>Fairplay et confiance</h3>
		<p>
			On considère en GN que tout effet qui nous est expliqué par une Organ ou une autre PJ doit
			être tenu pour vrai et doit être appliqué sur le moment. Par exemple, si une PJ vient vers un
			autre et lui explique qu’elle a empoisonné sa boisson et qu’elle meurt sur-le-champ, et bien
			cette dernière doit mourir immédiatement, sans discuter, et faire semblant qu’il ne sait pas
			qui l’a empoisonné. Bien entendu, utiliser des compétences que son personnage ne maîtrise pas
			est considéré comme de la triche, et ce n’est vraiment pas bien vu dans l’univers du GN…
		</p>

		<h3>Séparer jeu et réalité</h3>
		<p>
			Il faut encore ajouter quelques règles plus “morales”; la principale est la suivante : tout ce
			qui se dit et se fait dans le jeu n’a pas d’influence sur la réalité, et tout ce qui s’est
			passé dans la réalité n’en a pas sur le jeu. Il est très important de distinguer ces deux
			temps. Deux personnages qui se détestent ne sont pas incarnés par des ennemis jurés ; leur
			rôle leur impose cette relation, c’est tout. Un personnage se faisant insulter en jeu ne doit
			pas prendre ces mots personnellement contre lui, puisque c’est son PERSONNAGE qui est insulté.
			Mais attention ! Il est intolérable de se servir du GN pour se défouler sur les personnes que
			l’on n’apprécie pas ! Le jeu ne doit EN AUCUN CAS être utilisé de cette manière ! A nouveau,
			en cas de problème avec d’autres joueurs, il est possible d’avertir les Orgas.
		</p>

